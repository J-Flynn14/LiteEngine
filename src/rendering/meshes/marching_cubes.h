/// Pulls a sample sitting on a transition face inward by half a cell, matching the
/// slab Transvoxel::transitionSurface fills. Values are unchanged; only geometry moves.
inline void applyTransitionInset(const Config& config, int pad, const glm::ivec3& local,
                                 glm::vec3& position) noexcept {
    for (int axis = 0; axis < 3; ++axis) {
        const int negBit = 1 << (2 * axis);
        const int posBit = 1 << (2 * axis + 1);
        if ((config.transitionFaces & negBit) && local[axis] == pad) {
            position[axis] += detail::kTransitionInset * config.cellSize[axis];
        } else if ((config.transitionFaces & posBit) && local[axis] == pad + config.resolution[axis]) {
            position[axis] -= detail::kTransitionInset * config.cellSize[axis];
        }
    }
}

/// Samples a callback onto a grid. Separated so the sampling and the meshing can run
/// independently, and so a field can be reused across several surface() calls.
inline Field sample(const std::function<float(const glm::vec3&)>& field, const Config& config) {
    Field out;
    out.dimensions = config.sampleDimensions();
    if (config.resolution.x < 1 || config.resolution.y < 1 || config.resolution.z < 1) {
        log_error("MarchingCubes: resolution must be at least 1 cell per axis");
        return out;
    }
    if (config.padding < 0) {log_error("MarchingCubes: padding must be >= 0"); return out;}

    const glm::ivec3 base = config.gridOffset - glm::ivec3(config.padding);
    out.values.resize(static_cast<size_t>(out.dimensions.x) * out.dimensions.y * out.dimensions.z);
    size_t index = 0;
    for (int z = 0; z < out.dimensions.z; ++z) {
        for (int y = 0; y < out.dimensions.y; ++y) {
            for (int x = 0; x < out.dimensions.x; ++x) {
                out.values[index++] = field(config.positionOf(base + glm::ivec3(x, y, z)));
            }
        }
    }
    return out;
}

/// Extracts the isosurface as a pos3 + nrm3 indexed mesh. Normals come from the field
