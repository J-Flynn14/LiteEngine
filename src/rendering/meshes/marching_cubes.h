/// Half-cell inset applied to the fine chunk's boundary cells, leaving room for the
/// slab. MarchingCubes::Config::transitionFaces must match, or the two will not meet.
inline constexpr float kSlabDepth = 0.5f;

/// Meshes the transition cells covering one face of a chunk. Append the result to the
/// chunk's regular mesh; both must be generated with the same face in transitionFaces.
inline MeshData transitionSurface(const MarchingCubes::Field& field,
                                  const MarchingCubes::Config& config, Face face) {
    MeshData data;
    data.layout = VertexLayout::floats({3, 3});
    if (!field.isValid()) {
        log_error("Transvoxel: field is empty or its dimensions don't match its values");
        return data;
    }

    const int f = static_cast<int>(face);
    const int au = detail::kFaceBasis[f][0];
    const int av = detail::kFaceBasis[f][1];
    const int aw = detail::kFaceBasis[f][2];
    const int outward = detail::kFaceOutward[f];

    const int resU = (au == 0) ? config.resolution.x : (au == 1) ? config.resolution.y : config.resolution.z;
    const int resV = (av == 0) ? config.resolution.x : (av == 1) ? config.resolution.y : config.resolution.z;
    const int resW = (aw == 0) ? config.resolution.x : (aw == 1) ? config.resolution.y : config.resolution.z;
    if (resU % 2 || resV % 2) {
        log_error("Transvoxel: resolution across a transition face must be even");
        return data;
    }

    const glm::ivec3 base = config.gridOffset - glm::ivec3(config.padding);
    const int wPlane = (outward > 0) ? config.padding + resW : config.padding;

    std::unordered_map<uint64_t, unsigned int> vertexForEdge;

    // Local (u, v, w) sample coordinate -> global grid coordinate.
    const auto gridOf = [&](int u, int v) {
        glm::ivec3 g(0);
        g[au] = u; g[av] = v; g[aw] = wPlane;
        return base + g;
    };

    const auto emit = [&](const glm::ivec3& ga, const glm::ivec3& gb, bool fineSide) -> unsigned int {
        const uint64_t ka = (static_cast<uint64_t>(ga.z) * field.dimensions.y + ga.y) * field.dimensions.x + ga.x;
        const uint64_t kb = (static_cast<uint64_t>(gb.z) * field.dimensions.y + gb.y) * field.dimensions.x + gb.x;
        const uint64_t key = (ka < kb ? ka * 8192u + kb : kb * 8192u + ka) * 2 + (fineSide ? 1u : 0u);
        const auto found = vertexForEdge.find(key);
        if (found != vertexForEdge.end()) return found->second;

        const glm::ivec3 la = ga - base, lb = gb - base;
        const float va = field.at(la.x, la.y, la.z);
        const float vb = field.at(lb.x, lb.y, lb.z);
        const float d = vb - va;
        const float t = (std::abs(d) < 1e-12f) ? 0.5f
                      : glm::clamp((config.isoLevel - va) / d, 0.0f, 1.0f);

        glm::vec3 pa = config.positionOf(ga);
        glm::vec3 pb = config.positionOf(gb);
        // The fine-side contour is pulled in by half a cell; the coarse side stays on
        // the chunk boundary, which is where the neighbour's own contour sits.
        if (fineSide) {
            pa[aw] -= outward * kSlabDepth * config.cellSize[aw];
            pb[aw] -= outward * kSlabDepth * config.cellSize[aw];
        }
        const glm::vec3 position = pa + (pb - pa) * t;

        const glm::vec3 ga3 = MarchingCubes::detail::gradientAt(field, la.x, la.y, la.z);
        const glm::vec3 gb3 = MarchingCubes::detail::gradientAt(field, lb.x, lb.y, lb.z);
        glm::vec3 normal = ga3 + (gb3 - ga3) * t;
        const float len = glm::length(normal);
        normal = (len > 1e-8f) ? normal / len : glm::vec3(0.0f, 1.0f, 0.0f);

        const unsigned int index = static_cast<unsigned int>(data.vertices.size() / 6);
        data.vertices.insert(data.vertices.end(),
                             {position.x, position.y, position.z, normal.x, normal.y, normal.z});
        vertexForEdge.emplace(key, index);
        return index;
    };

    for (int cv = 0; cv < resV; cv += 2) {
        for (int cu = 0; cu < resU; cu += 2) {
            const auto sampleGrid = [&](int s) {
                const int src = (s < 9) ? s : detail::kCoarseSource[s - 9];
                return gridOf(cu + config.padding + (src % 3), cv + config.padding + (src / 3));
            };

            int configuration = 0;
            for (int s = 0; s < 9; ++s) {
                const glm::ivec3 l = sampleGrid(s) - base;
                if (field.at(l.x, l.y, l.z) < config.isoLevel) configuration |= (1 << s);
            }

            const int* triangles = detail::kTransitionTable[configuration];
            for (int i = 0; triangles[i] >= 0; i += 3) {
                unsigned int idx[3];
                bool degenerate = false;
                for (int k = 0; k < 3; ++k) {
                    const int e = triangles[i + k];
                    const bool fineSide = (e < 12);
                    idx[k] = emit(sampleGrid(detail::kTransitionEdges[e][0]),
                                  sampleGrid(detail::kTransitionEdges[e][1]), fineSide);
                }
                // Fine and coarse crossings can land on the same point; drop the sliver.
                if (idx[0] == idx[1] || idx[1] == idx[2] || idx[0] == idx[2]) degenerate = true;
                if (!degenerate) {
                    data.indices.push_back(idx[0]);
                    data.indices.push_back(idx[1]);
                    data.indices.push_back(idx[2]);
                }
            }
        }
    }
    return data;
}

