            int lo[3] = {x, y, z}, hi[3] = {x, y, z};
            const int limit = (ax == 0) ? d.x : (ax == 1) ? d.y : d.z;
            lo[ax] = (lo[ax] > 0) ? lo[ax] - 1 : lo[ax];
            hi[ax] = (hi[ax] < limit - 1) ? hi[ax] + 1 : hi[ax];
